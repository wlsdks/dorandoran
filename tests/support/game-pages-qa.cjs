if (process.env.FIREBASE_DATABASE_EMULATOR_HOST !== '127.0.0.1:9000' || process.env.FIREBASE_AUTH_EMULATOR_HOST !== '127.0.0.1:9099') throw new Error('Local demo emulators required');
const fs = require('node:fs'), path = require('node:path');
const { createRequire } = require('node:module');
const { chromium, expect } = require('@playwright/test');
const deps = createRequire(path.resolve(__dirname, '../../functions/package.json'));
const { initializeApp, deleteApp } = deps('firebase-admin/app');
const { getDatabase } = deps('firebase-admin/database');
const app = initializeApp({ projectId: 'demo-dorandoran', databaseURL: 'https://demo-dorandoran.firebaseio.com' }, 'game-pages-qa');
const db = getDatabase(app), sid = 'qa_game_pages', base = 'http://127.0.0.1:5175';
const folder = path.join('/tmp', 'dorandoran-game-pages-' + process.pid);
fs.mkdirSync(folder, { recursive: true });
let browser;
const errors = [];
(async () => {
  await db.ref(`sessions/${sid}`).set({ creatorId: 'legacy_master', courseId: 'course_a', courseName: '추첨 페이지 점검', status: 'active', currentMode: 'lottery', createdAt: Date.now(),
    participantCount: 7, participants: Object.fromEntries(Array.from({ length: 7 }, (_, i) => ['qa_draw_' + i, { nickname: ['윤서진', '김하늘', '이도윤', '박서연', '최민준', '한지우', '강예린'][i], joinedAt: 1, connections: { fixture: true } }])) });
  browser = await chromium.launch(process.platform === 'darwin' ? { channel: 'chrome' } : {});
  const teacher = await (await browser.newContext({ viewport: { width: 1512, height: 982 } })).newPage();
  const board = await (await browser.newContext({ viewport: { width: 1512, height: 982 } })).newPage();
  for (const page of [teacher, board]) page.on('pageerror', error => errors.push(error.message));
  await teacher.goto(base + '/admin');
  await teacher.getByPlaceholder('아이디').fill('qa-master');
  await teacher.getByPlaceholder('비밀번호').fill('TestFixture-Only-Strong8');
  await teacher.getByRole('button', { name: '로그인', exact: true }).click();
  await expect(teacher.getByRole('button', { name: '내 클래스', exact: true })).toBeVisible();
  await teacher.goto(base + '/admin?s=' + sid);
  await board.goto(base + '/live?s=' + sid);
  await teacher.getByRole('spinbutton', { name: '당첨자 수' }).fill('7');
  await teacher.getByRole('button', { name: '추첨 시작', exact: true }).click();
  await expect.poll(async () => (await db.ref(`sessions/${sid}/gameState/phase`).get()).val(), { timeout: 30_000 }).toBe('revealed');
  await expect(board.getByRole('heading', { name: '7명 당첨!', exact: true })).toBeVisible();
  await expect(board.getByText('1 / 2 · 12초마다 다음 당첨자', { exact: true })).toBeVisible();
  await board.waitForTimeout(650);
  await board.screenshot({ path: path.join(folder, 'first-page.png') });
  const before = (await db.ref(`sessions/${sid}/gameState`).get()).val();
  const resultBefore = (await db.ref(`sessions/${sid}/gameResult`).get()).val();
  await teacher.getByRole('button', { name: '다음 당첨자', exact: true }).click();
  await expect.poll(async () => (await db.ref(`sessions/${sid}/gameState/resultPage`).get()).val()).toBe(1);
  await expect(board.getByText('2 / 2 · 12초마다 다음 당첨자', { exact: true })).toBeVisible();
  await expect(board.getByText('#7 당첨', { exact: true })).toBeVisible();
  await board.waitForTimeout(650);
  await board.screenshot({ path: path.join(folder, 'last-page.png') });
  expect((await db.ref(`sessions/${sid}/gameState/winners`).get()).val()).toEqual(before.winners);
  expect(resultBefore.winners).toEqual(before.winners.map(({ id, nickname, employeeId }) => ({ id, nickname, ...(employeeId ? { employeeId } : {}) })));
  expect((await db.ref(`sessions/${sid}/gameResult`).get()).val()).toEqual(resultBefore);
  await expect.poll(async () => (await db.ref(`sessions/${sid}/gameState/resultPage`).get()).val(), { timeout: 15_000 }).toBe(0);
  await expect(board.getByText('1 / 2 · 12초마다 다음 당첨자', { exact: true })).toBeVisible();
  await expect(board.getByRole('button', { name: '다음 당첨자' })).toHaveCount(0);
  expect(errors).toEqual([]);
  console.log(JSON.stringify({ result: 'PASS', actualSevenPersonDraw: true, teacherBoardPageSync: true, timedPageRotation: true, winnersUnchanged: true, errors, screenshots: folder }));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  await browser?.close();
  await db.ref(`sessions/${sid}`).remove();
  await deleteApp(app);
});
